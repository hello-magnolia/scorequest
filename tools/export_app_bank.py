#!/usr/bin/env python3
"""
Publish the ScoreQuest Originals bank to the app.

Two targets, from the research folder (bank/SQ_ORIG/test.json is the built bank):

    python3 pipeline/export_app_bank.py --out ../scorequest/data/questions.js
        The static file the pages fall back to and the gate audits (verify_bank).

    SUPABASE_URL=https://xxxx.supabase.co SUPABASE_SERVICE_KEY=... \
    python3 pipeline/export_app_bank.py --supabase
        Upserts the questions table (what students see) and question_keys (what grades
        them) through Supabase's REST API with the service role key. The key is read from
        the environment only: never pass it on the command line or commit it. Rows for
        questions no longer in the bank are marked retired, not deleted, so old attempts
        keep their reference.

Add --approved-only to either target once reviews are done. Only questions with source
"scorequest-original" are exported: official College Board questions never leave this folder.
Standard library only, so it runs on a fresh Mac without pip.
"""
import argparse, json, os, sys, urllib.request, urllib.error
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load(bank_path, approved_only):
    b = json.loads(Path(bank_path).read_text())
    st = {s["id"]: s for s in b.get("stimuli", [])}
    out = []
    for it in b["items"]:
        if it.get("source") != "scorequest-original":
            raise SystemExit(f"{it['id']}: not an original, refusing to export")
        if approved_only and it.get("status") != "approved":
            continue
        q = {"id": it["id"], "section": it["section"], "domain": it["legacy_section"], "skill": it["skill"],
             "difficulty": it["difficulty_authored"], "type": it["type"], "status": it.get("status", "draft"),
             "stem": it["stem"], "explanation": it["explanation"]}
        if it.get("choices"):
            q["choices"] = [{k: c[k] for k in ("key", "text", "correct", "trap", "figure") if c.get(k) is not None} for c in it["choices"]]
        if it.get("answer"):
            q["accepted"] = it["answer"]["accepted"]
        for k in ("figure", "table", "mark"):
            if it.get(k):
                q[k] = it[k]
        s = st.get(it.get("stimulus"))
        if s:
            q["passage"] = {"kind": s["kind"], "intro": s.get("intro"), "parts": s["parts"],
                            "figures": s.get("figures") or []}
        out.append(q)
    return out


def write_static(out, path, approved_only):
    meta = {"exported": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), "count": len(out),
            "source": "ScoreQuest Originals", "approved_only": approved_only}
    js = ("/* Generated by the Scorequest Research pipeline (pipeline/export_app_bank.py). Do not edit by hand:\n"
          "   fix questions in originals/ there, rebuild, and export again. Only ScoreQuest Originals ship. */\n"
          "window.SQ_QUESTION_BANK = " + json.dumps({"meta": meta, "questions": out}, ensure_ascii=False, separators=(",", ":")) + ";\n")
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(js)
    print(f"exported {len(out)} questions to {path}")


# ---------------------------------------------------------------- supabase
def split_rows(out):
    """One row per question for the public table, one for the locked keys table."""
    qrows, krows = [], []
    for q in out:
        choices = None
        if q.get("choices"):
            choices = [{k: c[k] for k in ("key", "text", "figure") if k in c} for c in q["choices"]]
        qrows.append({"id": q["id"], "section": q["section"], "domain": q["domain"], "skill": q["skill"],
                      "difficulty": q["difficulty"], "type": q["type"], "status": q["status"], "stem": q["stem"],
                      "choices": choices, "passage": q.get("passage"), "figure": q.get("figure"), "table": q.get("table"),
                      "updated_at": datetime.now(timezone.utc).isoformat()})
        key = next((c["key"] for c in q.get("choices", []) if c.get("correct")), None)
        traps = {c["key"]: c["trap"] for c in q.get("choices", []) if c.get("trap")} or None
        krows.append({"question_id": q["id"], "correct_key": key, "accepted": q.get("accepted"),
                      "traps": traps, "explanation": q["explanation"]})
    return qrows, krows


def rest(url, key, path, method="GET", body=None, prefer=None):
    req = urllib.request.Request(url.rstrip("/") + "/rest/v1/" + path, method=method,
                                 data=json.dumps(body).encode() if body is not None else None)
    req.add_header("apikey", key)
    req.add_header("Authorization", "Bearer " + key)
    req.add_header("Content-Type", "application/json")
    if prefer:
        req.add_header("Prefer", prefer)
    try:
        with urllib.request.urlopen(req) as r:
            txt = r.read().decode()
            return json.loads(txt) if txt else None
    except urllib.error.HTTPError as e:
        raise SystemExit(f"Supabase {method} {path} failed: {e.code} {e.read().decode()[:400]}")


def publish_supabase(out):
    url, key = os.environ.get("SUPABASE_URL"), os.environ.get("SUPABASE_SERVICE_KEY")
    if not url or not key:
        raise SystemExit("set SUPABASE_URL and SUPABASE_SERVICE_KEY in the environment (service role key, never the anon key)")
    if key.startswith("sb_publishable") or key.startswith("eyJ") and '"role":"anon"' in key:
        raise SystemExit("that looks like the anon key; the pipeline needs the service role key (Settings > API)")
    qrows, krows = split_rows(out)
    for i in range(0, len(qrows), 100):
        rest(url, key, "questions", "POST", qrows[i:i + 100], "resolution=merge-duplicates,return=minimal")
    for i in range(0, len(krows), 100):
        rest(url, key, "question_keys", "POST", krows[i:i + 100], "resolution=merge-duplicates,return=minimal")
    live = {q["id"] for q in out}
    existing = rest(url, key, "questions?select=id&status=neq.retired") or []
    gone = [r["id"] for r in existing if r["id"] not in live]
    for qid in gone:
        rest(url, key, f"questions?id=eq.{qid}", "PATCH", {"status": "retired"}, "return=minimal")
    counts = rest(url, key, "questions?select=status") or []
    tally = {}
    for r in counts:
        tally[r["status"]] = tally.get(r["status"], 0) + 1
    print(f"upserted {len(qrows)} questions and {len(krows)} keys; retired {len(gone)}; table now {tally}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bank", default=str(ROOT / "bank" / "SQ_ORIG" / "test.json"))
    ap.add_argument("--out", help="write the static data/questions.js")
    ap.add_argument("--supabase", action="store_true", help="upsert into Supabase (needs SUPABASE_URL and SUPABASE_SERVICE_KEY)")
    ap.add_argument("--approved-only", action="store_true")
    a = ap.parse_args()
    if not a.out and not a.supabase:
        ap.error("pick a target: --out <file> and/or --supabase")
    out = load(a.bank, a.approved_only)
    if a.out:
        write_static(out, a.out, a.approved_only)
    if a.supabase:
        publish_supabase(out)


if __name__ == "__main__":
    main()
